// Writes docs/TEST_REPORT.md, docs/FORMULA_REFERENCE.md and docs/TOPIC_CHECKLIST.md
// from the same verification cases and data the app uses.
import { writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { CASES } from '../tests/cases.mjs';
import { matches } from '../tests/engine.test.mjs';
import * as E from '../app/js/engine/index.js';

const docs = new URL('../docs/', import.meta.url);
const fmt = (v) => (typeof v === 'number' ? (Math.abs(v) >= 1e6 || (Math.abs(v) < 1e-3 && v !== 0) ? v.toExponential(6) : String(Number(v.toPrecision(10)))) : String(v));
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/<sup>/g, '^').replace(/<\/sup>/g, '');

let unit = '';
try { unit = execFileSync('node', ['--test', 'tests/engine.test.mjs'], { cwd: new URL('..', import.meta.url).pathname, encoding: 'utf8' }); } catch (e) { unit = e.stdout || ''; }
const total = unit.match(/# tests (\d+)/)?.[1], pass = unit.match(/# pass (\d+)/)?.[1], fail = unit.match(/# fail (\d+)/)?.[1];

const rows = CASES.map((c) => { let a; try { a = c.run(); } catch (e) { a = `ERROR: ${e.message}`; } return { ...c, actual: a, ok: matches(c, a) }; });
const ok = rows.filter((r) => r.ok).length;
const byCalc = [...new Set(rows.map((r) => r.calc))];
await writeFile(new URL('TEST_REPORT.md', docs), `# Calculation test report

Generated by \`npm run report\` on ${new Date().toISOString().slice(0, 10)}.

- Automated test suite (\`npm test\`): **${pass} of ${total} tests passed, ${fail} failed.** This includes the verification table below plus invalid-input, boundary, security and practice-generator tests (tests/engine.test.mjs).
- Independently verified calculations: **${ok} of ${rows.length} passed**, across ${byCalc.length} calculator test groups.

## How the expected answers were obtained

Each expected value was worked out by hand from the textbook formula, using the constants in FORMULA_REFERENCE.md. The "Working" column shows that arithmetic. The expected values were written before the app's output was compared, and none was copied from it.

Four hand-calculated values contained arithmetic slips and were corrected by recomputing them by hand: K₄[Fe(CN)₆] (368.345, not 368.343), the Al₂O₃ theoretical yield (18.8943 g), heat from 32.0 g CH₄ (−1775.229 kJ), and ideal-gas moles at 25 °C (0.204370, not 0.204361). The last one was found because the test failed; the app's value matched the corrected hand calculation. Tolerances are relative (for example 1e-6 = one part per million) and only absorb floating-point rounding, not chemistry differences.

## Verification table

| Calculator | Test input | Expected (independent) | Working | Actual (app) | Result |
|---|---|---|---|---|---|
${rows.map((r) => `| ${cell(r.calc)} | ${cell(r.input)} | ${cell(fmt(r.expected))} | ${cell(r.work || '')} | ${cell(fmt(r.actual))} | ${r.ok ? 'PASS' : '**FAIL**'} |`).join('\n')}

## Other automated checks (tests/engine.test.mjs)

- Invalid formulas: empty, lower-case, unknown elements, unclosed brackets, zero subscripts, leading coefficients, HTML/script characters, over-long input.
- Equations: missing arrow, two arrows, element on one side only, impossible balance, typed coefficients checked.
- Atom conservation verified on four further equations (octane combustion, Fe₂O₃ + CO, NH₄NO₃, Ca(OH)₂ + H₃PO₄).
- Gas laws: below absolute zero, zero or negative pressure/amount, non-numeric and missing inputs, Celsius never used directly.
- Thermochemistry: ΔT = 0, sign mismatches, impossible calorimetry temperatures, missing ΔH°f data and user overrides, Ea < ΔH.
- Scientific calculator: refuses code such as \`alert(1)\` and \`constructor.constructor(...)\`, division by zero, log(0), sqrt(−1), unbalanced brackets.
- Output encoding: formulas containing < > are escaped before display.
- Practice: 540 generated questions (12 topics × 3 levels × 15 seeds) are reproducible from their seed and accept their own answer while rejecting a wrong one.

See OFFLINE_TEST_REPORT.md for the browser, installation, offline and mobile tests.
`);

const C = E.CONSTANTS;
await writeFile(new URL('FORMULA_REFERENCE.md', docs), `# Formula reference

All formulas implemented in CHEMATRIX. The same content is in the app's Formula library.

## Constants and data sources

| Constant | Value | Source |
|---|---|---|
${Object.values(C).map((c) => `| ${c.name} | ${c.value} ${c.unit} | ${c.source} |`).join('\n')}

- **Atomic masses:** ${E.ATOMIC_MASS_SOURCE}
- **Standard enthalpies of formation:** ${E.DHF_SOURCE}
- **Bond energies:** ${E.BOND_SOURCE}
- **Unit definitions:** 1 atm = 101.325 kPa = 760 torr; 1 mmHg = 133.322387 Pa; 1 bar = 100 kPa; 1 cal = 4.184 J; T(K) = T(°C) + 273.15.
- **Significant figures:** multiplication/division answers use the fewest significant figures among measured inputs; sums and differences (ΔT, °C→K) use decimal places. Exact numbers (coefficients, N_A, 273.15, unit definitions) never limit precision. Trailing zeros without a decimal point (for example "100") are ambiguous; the app counts them as significant and shows a note.

${[...new Set(E.FORMULAS.map((f) => f.topic))].map((t) => `## ${t}\n\n${E.FORMULAS.filter((f) => f.topic === t).map((f) => `### ${f.name}\n\n\`${f.equation}\`\n\n| Symbol | Meaning | Units |\n|---|---|---|\n${f.vars.map(([a, b, c]) => `| ${cell(a)} | ${cell(b)} | ${cell(c)} |`).join('\n')}\n\n${f.explanation}\n\n- Conditions: ${f.conditions}\n- Example: ${f.example}\n- Calculator: \`#/${f.tool}\``).join('\n\n')}`).join('\n\n')}
`);

await writeFile(new URL('TOPIC_CHECKLIST.md', docs), `# Topic coverage checklist

The checklist is configurable in \`app/js/engine/library.js\` (TOPIC_CHECKLIST) and is shown in the app under Settings → Topic checklist.

**Action needed:** the three module titles do not prove that every topic your instructor requires is covered. Compare this list with the official topic list and change the "To confirm" items (or add new ones).

${E.TOPIC_CHECKLIST.map((m) => `## ${m.module}\n\n| Topic | Status | Where |\n|---|---|---|\n${m.items.map(([l, p, d]) => `| ${l} | ${d ? 'Covered' : 'To confirm with instructor (not implemented)'} | ${p ? `\`#/${p}\`` : '—'} |`).join('\n')}`).join('\n\n')}
`);
console.log(`docs written: ${ok}/${rows.length} verification cases pass; unit tests ${pass}/${total}`);
